#!/usr/bin/env python3
"""Writes the Zap mark as Android vector drawables into res/ (the in-app logo and the launcher foreground).

The mark is ../zap-app/DESIGN.md's: a chubby bolt (the path filled and stroked 12 wide with round joins) with a face
cut out of it. Vector drawables have no masks, so the face is a clip-path: a square around the mark with the eyes and
the mouth's outline wound the other way, which the nonzero rule leaves out. Run it after changing the mark:
`python3 dev/mark.py`.
"""
import math
import os

BOLT = "M62 6L16 58H44L34 94L84 38H57L70 6Z"
EYES = [(41, 47), (58, 45)]
EYE_R = 3.8
MOUTH = (44, 55.5, 51, 61.5, 58, 53.5)  # rest: a smile, quadratic x0 y0 cx cy x1 y1
MOUTH_W = 3.6

INK = "#16182B"
SPARK = "#FFD23F"


def area(points):
    return sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(points, points[1:] + points[:1])) / 2


def wound(points, sign):
    """The polygon, wound so its signed area has [sign]."""
    return points if (area(points) > 0) == (sign > 0) else points[::-1]


def circle(cx, cy, r, n=24):
    return [(cx + r * math.cos(2 * math.pi * i / n), cy + r * math.sin(2 * math.pi * i / n)) for i in range(n)]


def stroke_outline(q, width, n=24):
    """The outline of a quadratic curve stroked [width] wide with round caps."""
    x0, y0, cx, cy, x1, y1 = q
    h = width / 2

    def at(t):
        u = 1 - t
        p = (u * u * x0 + 2 * u * t * cx + t * t * x1, u * u * y0 + 2 * u * t * cy + t * t * y1)
        d = (2 * u * (cx - x0) + 2 * t * (x1 - cx), 2 * u * (cy - y0) + 2 * t * (y1 - cy))
        length = math.hypot(*d)
        return p, (-d[1] / length, d[0] / length)

    ts = [i / n for i in range(n + 1)]
    left = [(p[0] + h * nx, p[1] + h * ny) for p, (nx, ny) in map(at, ts)]
    right = [(p[0] - h * nx, p[1] - h * ny) for p, (nx, ny) in map(at, reversed(ts))]

    def cap(t, side):
        """Half a turn around an end, from one side of the stroke to the other, through the outward direction."""
        (px, py), (nx, ny) = at(t)
        a0 = math.atan2(side * ny, side * nx)
        return [(px + h * math.cos(a0 - math.pi * i / 8), py + h * math.sin(a0 - math.pi * i / 8)) for i in range(1, 8)]

    return left + cap(1, 1) + right + cap(0, -1)


def path(points):
    return "M" + "L".join(f"{x:.2f},{y:.2f}" for x, y in points) + "Z"


def face_clip():
    square = [(-20, -20), (120, -20), (120, 120), (-20, 120)]
    holes = [circle(x, y, EYE_R) for x, y in EYES] + [stroke_outline(MOUTH, MOUTH_W)]
    return path(wound(square, 1)) + "".join(path(wound(hole, -1)) for hole in holes)


def mark(color, scale, translate):
    return f'''    <group android:scaleX="{scale}" android:scaleY="{scale}" android:translateX="{translate}" android:translateY="{translate}">
        <clip-path android:pathData="{face_clip()}" />
        <path
            android:fillColor="{color}"
            android:strokeColor="{color}"
            android:strokeWidth="12"
            android:strokeLineJoin="round"
            android:pathData="{BOLT}" />
    </group>'''


def vector(comment, size, viewport, body):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by dev/mark.py: edit that, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
{body}
</vector>
'''


def write(path_, text):
    os.makedirs(os.path.dirname(path_), exist_ok=True)
    with open(path_, "w") as f:
        f.write(text)


root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "res")
# The mark's box is -10..110: shifted by 10 into a 120 viewport.
write(os.path.join(root, "drawable", "ic_brand_logo.xml"), vector("The Zap mark in ink, for light screens.", 96, 120, mark(INK, 1, 10)))
write(os.path.join(root, "drawable-night", "ic_brand_logo.xml"), vector("The Zap mark in spark, for dark screens.", 96, 120, mark(SPARK, 1, 10)))
# Launcher: the 120 box scaled to 60 inside the 108 canvas, centred, within the adaptive icon's 66dp safe zone. One
# colour, so themed (monochrome) icons show it too; the background is spark (brand_launcher_background).
scale = 0.5
write(
    os.path.join(root, "drawable", "ic_launcher_foreground.xml"),
    vector("Launcher mark: ink on spark, in one colour.", 108, 108, mark(INK, scale, (108 - 120 * scale) / 2 + 10 * scale)),
)
